function table(rows, widths, hl = []) {
  return new Table({
    visuallyRightToLeft: true, width: { size: W, type: WidthType.DXA }, columnWidths: widths,
    rows: rows.map((row, ri) => new TableRow({
      tableHeader: ri === 0,
      children: row.map((c, i) => new TableCell({
        borders, width: { size: widths[i], type: WidthType.DXA }, verticalAlign: VerticalAlign.CENTER,
        margins: { top: 40, bottom: 40, left: 70, right: 70 },
        shading: ri === 0 ? { fill: "E7E6E6", type: ShadingType.CLEAR, color: "auto" }
          : hl.includes(ri) ? { fill: "EEF4FB", type: ShadingType.CLEAR, color: "auto" } : undefined,
        children: [new Paragraph({
          bidirectional: true, spacing: { after: 0, line: 260 },
          alignment: i === 0 ? AlignmentType.START : AlignmentType.CENTER,
          children: runs(String(c), { size: 20, bold: ri === 0 }),
        })],
      })),
    })),
  });
}

