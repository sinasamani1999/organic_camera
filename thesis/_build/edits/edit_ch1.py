from wdoc import Doc, ptext, q, fa_dash

d = Doc("/home/claude/w/ch1.docx")


def replace_in_runs(p, old, new):
    for t in p.iter(q("t")):
        if t.text and old in t.text:
            t.text = t.text.replace(old, fa_dash(new))
            return
    raise KeyError(old[:50])


